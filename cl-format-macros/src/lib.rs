#![doc = r#"Procedural macros for `cl-format`.

Provides two procedural macros:

1. `#[derive(TildeAble)]` on `TildeKind`: generates the `TildeAble` trait with default `format_<variant>` methods for each value-consuming directive variant.

```rust,ignore
#[derive(Debug, PartialEq, TildeAble)]
pub enum TildeKind<'a> {
    /// ~C ~:C
    Char(CharKind),

    /// ~$ ~5$ ~f
    Float(Option<&'a str>),

    /// ~d ~:d ~:@d
    Digit(Option<&'a str>),

    /// ~a
    Va,

    /// loop
    Loop((Vec<Tilde<'a>>, TildeLoopKind)),

    /// text inside the tilde
    Text(&'a str),

    /// vec
    VecTilde(Vec<Tilde<'a>>),
}
```

which expands to:

```rust,ignore
pub trait TildeAble: Debug {
    fn len(&self) -> usize { 1 }
    fn as_cond_index(&self) -> Option<usize> { None }
    fn as_cond_bool(&self) -> Option<bool> { None }

    fn format_char(&self, _tkind: &TildeKind, _buf: &mut String) -> Result<()> {
        Err(TildeError::new(ErrorKind::RevealError, "cannot reveal to Char").into())
    }
    fn format_va(&self, _tkind: &TildeKind, _buf: &mut String) -> Result<()> {
        Err(TildeError::new(ErrorKind::RevealError, "cannot reveal to Va").into())
    }
    // ...and other format_<variant> methods
}
```

2. `cl_format_compile_time!`: validates literal format strings and argument arity at compile time, expanding flat format strings into direct buffer writes and loop/conditional format strings into `OnceLock<ControlStr<'static>>` + `TupleArgs` dispatch.
"#]

use anyhow::Result;

use proc_macro::TokenStream;
use proc_macro2::{Ident, Literal, Span};
use quote::quote;
use syn::{parse_macro_input, spanned::Spanned, Attribute, Data, DataEnum, DeriveInput, Variant};

#[proc_macro_derive(TildeAble, attributes(implTo))]
pub fn derive_tilde_able(input: TokenStream) -> TokenStream {
    let input = parse_macro_input!(input as DeriveInput);

    let mut all_default_methods = vec![];

    match input.data {
        Data::Enum(DataEnum { ref variants, .. }) => {
            let all_vars = variants.iter().map(|var| parse_variant_attrs(var));

            all_vars.for_each(|(field, _tys)| {
                if matches!(
                    field.as_str(),
                    "Star" | "LoopEnd" | "Tildes" | "Text" | "VecTilde"
                ) {
                    return;
                }
                let fname = Ident::new(
                    &(String::from("format_") + &field.to_lowercase()),
                    Span::call_site(),
                );

                let err_msg = Literal::string(&format!("cannot reveal to {}", field));

                // add default format_<variant> methods directly to TildeAble
                all_default_methods.push(quote! {
                    fn #fname(&self, _tkind: &TildeKind, _buf: &mut String) -> Result<()> {
                        Err(TildeError::new(ErrorKind::RevealError, #err_msg).into())
                    }
                });
            });
        }
        _ => panic!("only support the enum"),
    };

    // trait TildeAble definition
    let tilde_able_trait = quote! {
        /// TildeAble is used for formatting types according to the specific tilde directive.
        ///
        /// Generated by `cl-format-macro`.
        pub trait TildeAble: Debug {
            fn len(&self) -> usize {
                1
            }
            fn as_cond_index(&self) -> Option<usize> {
                None
            }
            fn as_cond_bool(&self) -> Option<bool> {
                None
            }
            #(#all_default_methods)*
        }
    };

    tilde_able_trait.into()
}

/// return the field Ident and all types implTo. Empty if there is no implTo types
fn parse_variant_attrs(variant: &Variant) -> (String, impl Iterator<Item = Ident> + '_) {
    let all_impl_to_type = variant
        .attrs
        .iter()
        .filter(|attr| attr.path().get_ident().map(|d| d.to_string()) == Some("implTo".to_string()))
        .map(|attr| get_types_impl_to(attr).unwrap())
        .flatten();

    let field = variant.ident.to_string();

    (field.clone(), all_impl_to_type)
}

/// parse the `implTo` attribute
fn get_types_impl_to(attribute: &Attribute) -> Result<impl Iterator<Item = Ident>> {
    let mut result = vec![];
    attribute.parse_nested_meta(|meta| {
        result.push(
            meta.path
                .get_ident()
                .ok_or(syn::Error::new(meta.path.span(), "get_ident issue"))?
                .clone(),
        );
        Ok(())
    })?;

    Ok(result.into_iter())
}

